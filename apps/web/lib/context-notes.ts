/**
 * Context notes: readers question a record, the artist answers, others rate. Shown only when rated
 * helpful by enough people (services/evidence/src/context-notes.ts has the rules). The wording
 * never calls a piece or a person fake: a note is a question about the record, with what was seen.
 */
export type Concern = "ai_generated" | "process_mismatch" | "copied" | "other";
export type NoteStatus = "needs_ratings" | "shown" | "not_shown";

export interface ContextNote {
  id: number;
  pieceId: string;
  author: string;
  concern: Concern;
  body: string;
  asksEvidence: boolean;
  createdAt: number;
  status: NoteStatus;
  ratings: { helpful: number; total: number };
  publicFramesAtNote: number;
  response: { body: string; at: number; publicFramesAtResponse: number } | null;
  myRating?: { helpful: boolean; reason: string } | null;
}

export const CONCERN_TEXT: Record<Concern, string> = {
  ai_generated: "May have been generated by AI",
  process_mismatch: "The making does not match the finished piece",
  copied: "May be copied or traced from another work",
  other: "Something else about this record",
};

export const HELPFUL_TEXT: Record<string, string> = {
  specific_details: "Points to specific details in the record",
  names_useful_evidence: "Asks for evidence that would settle it",
  fair_tone: "Fair and respectful",
};
export const UNHELPFUL_TEXT: Record<string, string> = {
  speculation: "Guesswork, nothing specific",
  ignores_the_record: "Ignores what the record already shows",
  personal_attack: "About the person, not the work",
  artist_answered: "The artist's answer settles it",
};

export const NOTE_MIN_CHARS = 40;

export function ratingLine(n: Pick<ContextNote, "ratings" | "status">) {
  const { helpful, total } = n.ratings;
  if (n.status === "shown") return `Rated helpful by ${helpful} of ${total} people`;
  if (n.status === "not_shown") return `Rated not helpful by ${total - helpful} of ${total} people`;
  return total === 0 ? "No ratings yet" : `${total} rating${total === 1 ? "" : "s"} so far — needs more before it is shown`;
}

/** What the artist added since the note (frames made public), if anything. */
export function addedSince(n: ContextNote) {
  if (!n.response) return null;
  const more = n.response.publicFramesAtResponse - n.publicFramesAtNote;
  return more > 0 ? `Since this note, the artist made ${more} more frame${more === 1 ? "" : "s"} of the making public.` : null;
}
